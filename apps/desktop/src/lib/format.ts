/** Formatting helpers for model sizes, audit timestamps and data freshness. */

export function formatBytes(bytes: number | null | undefined): string {
  if (bytes === null || bytes === undefined || !Number.isFinite(bytes) || bytes < 0) return "—";
  if (bytes < 1024) return `${bytes} B`;
  const units = ["KB", "MB", "GB", "TB"];
  let value = bytes / 1024;
  let unit = 0;
  while (value >= 1000 && unit < units.length - 1) {
    value /= 1024;
    unit += 1;
  }
  return `${value >= 10 ? value.toFixed(0) : value.toFixed(1)} ${units[unit]}`;
}

export function percent(done: number | undefined, total: number | null | undefined): number | null {
  if (!total || total <= 0 || done === undefined || done < 0) return null;
  return Math.min(100, Math.round((done / total) * 100));
}

/** UTC offset label such as "GMT+7" for the given date in the local timezone. */
export function offsetLabel(date: Date): string {
  const minutes = -date.getTimezoneOffset();
  const sign = minutes >= 0 ? "+" : "-";
  const abs = Math.abs(minutes);
  const h = Math.floor(abs / 60);
  const m = abs % 60;
  return `GMT${sign}${h}${m ? `:${String(m).padStart(2, "0")}` : ""}`;
}

/** Local "dd/MM HH:mm" for an ISO-8601 audit timestamp (stored in UTC). */
export function formatLocal(iso: string | null | undefined, locale = "vi-VN"): string {
  if (!iso) return "—";
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return "—";
  return date.toLocaleString(locale, {
    day: "2-digit",
    month: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    hour12: false,
  });
}

export function formatDuration(ms: number | null | undefined): string {
  if (ms === null || ms === undefined || !Number.isFinite(ms) || ms < 0) return "—";
  const total = Math.round(ms / 1000);
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = total % 60;
  if (h) return `${h}h${String(m).padStart(2, "0")}m`;
  if (m) return `${m}m${String(s).padStart(2, "0")}s`;
  return `${s}s`;
}

/** Freshness bucket for the "updated at" label: fresh < 2 min, stale otherwise. */
export function isStale(fetchedAt: Date | null, now: Date, maxAgeMs = 120_000): boolean {
  return !fetchedAt || now.getTime() - fetchedAt.getTime() > maxAgeMs;
}
